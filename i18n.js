let LANG = 'en';
const I18N_ATTRS = ['alt', 'placeholder', 'aria-label', 'title'];
const normText = s => s.replace(/\s+/g, ' ').trim();

function t(s) {
    return LANG === 'ru' && RU[s] ? RU[s] : s;
}

function translateTree(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            const p = node.parentElement;
            if (!p || p.closest('script, style, [data-no-i18n]')) return NodeFilter.FILTER_REJECT;
            return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
        }
    });
    let node;
    while ((node = walker.nextNode())) {
        if (node.__orig === undefined) node.__orig = node.nodeValue;
        const key = normText(node.__orig);
        if (LANG === 'ru' && RU[key]) {
            const lead = node.__orig.match(/^\s*/)[0];
            const trail = node.__orig.match(/\s*$/)[0];
            node.nodeValue = lead + RU[key] + trail;
        } else {
            node.nodeValue = node.__orig;
        }
    }
    root.querySelectorAll('*').forEach(el => {
        I18N_ATTRS.forEach(attr => {
            if (!el.hasAttribute(attr)) return;
            if (!el.__origAttrs) el.__origAttrs = {};
            if (el.__origAttrs[attr] === undefined) el.__origAttrs[attr] = el.getAttribute(attr);
            const orig = el.__origAttrs[attr];
            el.setAttribute(attr, LANG === 'ru' && RU[normText(orig)] ? RU[normText(orig)] : orig);
        });
    });
}

let metaOrig = null;
function applyLang(lang, onChange) {
    LANG = lang === 'ru' ? 'ru' : 'en';
    document.documentElement.lang = LANG;
    const desc = document.querySelector('meta[name="description"]');
    if (!metaOrig) metaOrig = { title: document.title, description: desc ? desc.content : '' };
    document.title = LANG === 'ru' ? META_RU.title : metaOrig.title;
    if (desc) desc.content = LANG === 'ru' ? META_RU.description : metaOrig.description;
    translateTree(document.body);
    document.querySelectorAll('[data-lang]').forEach(b => b.classList.toggle('active', b.dataset.lang === LANG));
    if (onChange) onChange(LANG);
}

function initLang(onChange) {
    const root = document.documentElement;
    const home = root.dataset.homeEn ? { en: root.dataset.homeEn, ru: root.dataset.homeRu } : null;
    if (home) {
        // the home page exists as two real pages: index.html (EN) and ru.html (RU)
        const pageLang = root.lang === 'ru' ? 'ru' : 'en';
        const fromUrl = new URLSearchParams(location.search).get('lang');
        // only a language picked with the EN/RU switch is remembered; otherwise follow the browser language
        let chosen = null; try { chosen = localStorage.getItem('langChoice'); } catch (e) {}
        const bot = /bot|crawl|spider|slurp|yandex|google|bing|lighthouse/i.test(navigator.userAgent);
        const langs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || '']);
        const browser = (langs[0] || '').toLowerCase().startsWith('ru') ? 'ru' : 'en';
        let want = null;
        if (fromUrl === 'ru' || fromUrl === 'en') want = fromUrl;
        else if (!bot) want = (chosen === 'ru' || chosen === 'en') ? chosen : browser;
        if (want && want !== pageLang) { location.replace(home[want] + location.hash); return; }
        applyLang(pageLang, onChange);
        document.querySelectorAll('[data-lang]').forEach(b => b.addEventListener('click', () => {
            const l = b.dataset.lang;
            try { localStorage.setItem('langChoice', l); } catch (e) {}
            if (l !== pageLang) location.href = home[l] + location.hash;
        }));
        return;
    }
    let lang = null;
    const fromUrl = new URLSearchParams(location.search).get('lang');
    if (fromUrl === 'ru' || fromUrl === 'en') lang = fromUrl;
    if (!lang) { try { lang = localStorage.getItem('lang'); } catch (e) {} }
    if (!lang) lang = (navigator.language || '').toLowerCase().startsWith('ru') ? 'ru' : 'en';
    applyLang(lang, onChange);
    document.querySelectorAll('[data-lang]').forEach(b =>
        b.addEventListener('click', () => applyLang(b.dataset.lang, onChange)));
}
